-- ---------------------------------------------------------------------
-- 🔑 期初入库流水
--
-- 为什么必须有这一步：
-- 库存是"账本（inventory_transaction）推导出来的"数据，任何数量变动都应有对应流水。
-- 如果只在 material_inventory 里塞一个初始数量而没有流水，
-- 对账接口会立刻报 QUANTITY_DIFF（库存表 1000 vs 流水累加 0）——
-- 这不是 bug，而是对账在正确地发现"账实不符"。
--
-- 所以初始化库存必须同时生成一条"期初入库"流水（transaction_type=1），
-- 这样 SUM(流水) == 库存表现有量，对账才能通过，后续任何偏差才是真异常。
-- ---------------------------------------------------------------------
INSERT INTO inventory_transaction
    (transaction_no, material_id, material_code, warehouse_id, batch_no, transaction_type,
     quantity, before_quantity, after_quantity, before_reserved, after_reserved,
     biz_type, biz_no, operator_id, operator_name, remark)
SELECT CONCAT('TX-INIT-', LPAD(material_id, 3, '0')),
       material_id,
       material_code,
       1,
       CONCAT('MB-INIT-', LPAD(material_id, 3, '0')),
       1,                                  -- 1-入库
       quantity,                           -- 变动量 = 期初数量
       0.0000,                             -- 变动前
       quantity,                           -- 变动后
       0.0000,
       0.0000,
       '期初入库',
       CONCAT('INIT-', LPAD(material_id, 3, '0')),
       0,
       'system',
       '系统初始化期初库存'
FROM material_inventory;


